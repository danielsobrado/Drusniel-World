import fs from 'node:fs';
import yaml from 'js-yaml';

const root = new URL('../src/editor/construction/config/', import.meta.url);
const source = yaml.load(fs.readFileSync(new URL('wall-growth.yml', root), 'utf8'));
if (source.version !== 1) throw new Error('Unsupported wall growth version.');
const ranges = { cellSize: [1, 10], chance: [0, 1], maximumHeight: [0.1, 3], stems: [1, 3],
  nodes: [2, 10], leavesPerNode: [1, 5], spread: [0, 0.6], standOff: [0.02, 0.2],
  clearance: [0.05, 0.5], maxLeavesPerModule: [1, 512] };
for (const [key, profile] of Object.entries(source.styles)) {
  for (const [field, [min, max]] of Object.entries(ranges)) {
    const value = profile[field];
    if (!Number.isFinite(value) || value < min || value > max) throw new Error(`Invalid ${key}.${field}`);
  }
  for (const field of ['stems', 'nodes', 'leavesPerNode', 'maxLeavesPerModule']) {
    if (!Number.isInteger(profile[field])) throw new Error(`Non-integer ${key}.${field}`);
  }
  if (!Array.isArray(profile.leafRadius) || profile.leafRadius.length !== 2
    || !profile.leafRadius.every(v => Number.isFinite(v) && v >= 0.02 && v <= 0.25)
    || profile.leafRadius[0] > profile.leafRadius[1]) throw new Error(`Invalid ${key}.leafRadius`);
  if (!Array.isArray(profile.palette) || !profile.palette.length
    || !profile.palette.every(v => /^#[0-9a-f]{6}$/i.test(v))) throw new Error(`Invalid ${key}.palette`);
  if (profile.ground) {
    for (const [field, [min, max]] of Object.entries({ cellSize: [0.5, 4], reach: [0.05, 0.5],
      maxDetailsPerModule: [1, 128], flowerChance: [0, 1], pebbleChance: [0, 1], mossChance: [0, 1] })) {
      const value = profile.ground[field];
      if (!Number.isFinite(value) || value < min || value > max) throw new Error(`Invalid ${key}.ground.${field}`);
    }
    if (!Number.isInteger(profile.ground.maxDetailsPerModule)) throw new Error(`Non-integer ${key}.ground.maxDetailsPerModule`);
  }
}
const output = '// Generated by tools/generate-construction-growth.mjs; edit wall-growth.yml.\n'
  + `const profiles = ${JSON.stringify(source.styles, null, 2)};\n`
  + 'for (const profile of Object.values(profiles)) {\n'
  + '  Object.freeze(profile.palette); Object.freeze(profile.leafRadius); if (profile.ground) Object.freeze(profile.ground); Object.freeze(profile);\n}\n'
  + 'export const CONSTRUCTION_GROWTH_PROFILES = Object.freeze(profiles);\n';
const target = new URL('ConstructionGrowthProfiles.generated.js', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Wall growth config is stale.');
} else fs.writeFileSync(target, output);
