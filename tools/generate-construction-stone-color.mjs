import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../src/editor/construction/config/', import.meta.url));
const option = (name, fallback) => {
  const index = process.argv.indexOf(`--${name}`);
  return index < 0 ? fallback : process.argv[index + 1];
};
const source = yaml.load(fs.readFileSync(option('source', path.join(root, 'construction-stone-color.yml')), 'utf8'));
if (source.version !== 1 || !source.defaults || !source.styles) throw new Error('Invalid stone color configuration.');
const profiles = { default: source.defaults };
for (const [key, value] of Object.entries(source.styles)) profiles[key] = {
  ...source.defaults, ...value,
  value: { ...source.defaults.value, ...value.value },
  outlier: { ...source.defaults.outlier, ...value.outlier },
  categories: { ...source.defaults.categories, ...value.categories },
};
const range = (value, min, max, name) => {
  if (!Number.isFinite(value) || value < min || value > max) throw new Error(`Invalid ${name}.`);
};
const rgb = (value, name) => {
  if (!Array.isArray(value) || value.length !== 3) throw new Error(`Invalid ${name}.`);
  for (const channel of value) range(channel, 0.2, 2, name);
};
for (const [name, profile] of Object.entries(profiles)) {
  if (typeof profile.enabled !== 'boolean') throw new Error(`Invalid ${name}.enabled.`);
  for (const key of ['strength', 'warmChance', 'neutralChance']) range(profile[key], 0, 1, `${name}.${key}`);
  range(profile.value.min, 0.2, 2, `${name}.value.min`);
  range(profile.value.max, profile.value.min, 2, `${name}.value.max`);
  rgb(profile.warm, `${name}.warm`); rgb(profile.cool, `${name}.cool`);
  rgb(profile.outlier.multiplier, `${name}.outlier.multiplier`);
  range(profile.outlier.chance, 0, 1, `${name}.outlier.chance`);
  for (const value of Object.values(profile.categories)) range(value, 0, 1, `${name}.categories`);
  if (profile.patches) {
    range(profile.patches.strength, 0, 1, `${name}.patches.strength`);
    range(profile.patches.span, 0.5, 10, `${name}.patches.span`);
    range(profile.patches.rise, 0.5, 10, `${name}.patches.rise`);
    for (const key of ['pale', 'ochre', 'peach']) rgb(profile.patches[key], `${name}.patches.${key}`);
  }
}
const output = '// Generated by tools/generate-construction-stone-color.mjs; edit construction-stone-color.yml.\n'
  + 'function freeze(value) {\n  for (const child of Object.values(value)) if (child && typeof child === "object") freeze(child);\n  return Object.freeze(value);\n}\n'
  + `export const CONSTRUCTION_STONE_COLOR_PROFILES = freeze(${JSON.stringify(profiles, null, 2)});\n`
  + 'export function constructionStoneColorProfile(key) {\n  return CONSTRUCTION_STONE_COLOR_PROFILES[key] ?? CONSTRUCTION_STONE_COLOR_PROFILES.default;\n}\n';
const target = option('out', path.join(root, 'ConstructionStoneColorProfiles.generated.js'));
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Stone color config is stale.');
} else fs.writeFileSync(target, output);
